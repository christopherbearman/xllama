"""Embed uwp/web/index.html into uwp/web-ui-html.h (fork addition).

The LAN API serves the page at GET /ui. MSVC caps a single string literal at
~16 KB, so the HTML is split into raw-string chunks that the compiler
concatenates. Re-run after editing the page:  python3 scripts/embed-web-ui.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "uwp/web/index.html").read_text(encoding="utf-8")
assert ')XUI"' not in src, "delimiter collision"
data = src.encode("utf-8")
chunks, i = [], 0
while i < len(data):
    j = min(i + 12000, len(data))
    while j < len(data) and (data[j] & 0xC0) == 0x80:  # never split a UTF-8 sequence
        j -= 1
    chunks.append(data[i:j].decode("utf-8"))
    i = j
body = "\n".join(f'    R"XUI({c})XUI"' for c in chunks)
out = f"""// Copyright (c) 2024 Gianluca Mazza
// SPDX-License-Identifier: MIT
// GENERATED by scripts/embed-web-ui.py from uwp/web/index.html. Do not edit.
#pragma once

// clang-format off
inline const char* web_ui_html() {{
    return
{body};
}}
// clang-format on
"""
(ROOT / "uwp/web-ui-html.h").write_text(out, encoding="utf-8")
print(f"wrote uwp/web-ui-html.h: {len(data)} bytes in {len(chunks)} chunks")
