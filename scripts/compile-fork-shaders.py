#!/usr/bin/env python3
"""Compile the fork's IQ3_XXS / IQ4_XS D3D12 matmul kernels to DXIL headers.

Runs in the Windows CI before the UWP build (the Windows SDK ships dxc.exe);
set DXC=... to use another dxc. Writes shaders/generated/
ggml_d3d12_mmv_{iq3_xxs,iq4_xs}_t{64,128}_dxil.h in the same format as
scripts/compile-gpugemv-shader.sh.
"""
import glob
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = [("iq3_xxs", "Iq3Xxs"), ("iq4_xs", "Iq4Xs"), ("q5_k", "Q5K")]
# Tiled prefill variants (TILE columns per group): shaders/ggml_d3d12_mmt_*.hlsl
TILE_TARGETS = [("iq3_xxs", "Iq3Xxs"), ("iq4_xs", "Iq4Xs"), ("q4_k", "Q4K"), ("q5_k", "Q5K"), ("q6_k", "Q6K")]
TILE = 8
WIDTHS = [64, 128]


def find_dxc() -> str:
    env = os.environ.get("DXC")
    if env:
        return env
    hits = sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\dxc.exe"))
    if hits:
        return hits[-1]
    sys.exit("dxc not found: set DXC=path/to/dxc")


def emit(data: bytes, out: Path, source: str, symbol: str) -> None:
    lines = [
        "// AUTO-GENERATED by scripts/compile-fork-shaders.py — do not edit.",
        f"// Source: {source} (cs_6_4 CSMain)",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        f"// {len(data)} bytes DXIL",
        "// clang-format off",
        f"static const uint8_t {symbol}[] = {{",
    ]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")
    lines += ["};", f"static const size_t {symbol}Size = {len(data)};", "// clang-format on"]
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(data)} bytes)")


def main() -> None:
    dxc = find_dxc()
    print("dxc:", dxc)
    gen = ROOT / "shaders" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    for name, camel in TARGETS:
        src = ROOT / "shaders" / f"ggml_d3d12_mmv_{name}.hlsl"
        for w in WIDTHS:
            with tempfile.TemporaryDirectory() as td:
                obj = Path(td) / "out.dxil"
                cmd = [dxc, "-T", "cs_6_4", "-E", "CSMain", "-D", f"NUM_THREADS={w}",
                       "-I", str(ROOT / "shaders"), "-Fo", str(obj), str(src)]
                subprocess.run(cmd, check=True)
                emit(obj.read_bytes(), gen / f"ggml_d3d12_mmv_{name}_t{w}_dxil.h",
                     f"shaders/ggml_d3d12_mmv_{name}.hlsl -D NUM_THREADS={w}",
                     f"kGgmlD3d12Mmv{camel}T{w}Dxil")
    # Flash attention (one blob, 64 threads fixed in the shader).
    src = ROOT / "shaders" / "ggml_d3d12_fa.hlsl"
    with tempfile.TemporaryDirectory() as td:
        obj = Path(td) / "out.dxil"
        subprocess.run([dxc, "-T", "cs_6_4", "-E", "CSMain", "-I", str(ROOT / "shaders"),
                        "-Fo", str(obj), str(src)], check=True)
        emit(obj.read_bytes(), gen / "ggml_d3d12_fa_dxil.h", "shaders/ggml_d3d12_fa.hlsl",
             "kGgmlD3d12FaDxil")
    for name, camel in TILE_TARGETS:
        src = ROOT / "shaders" / f"ggml_d3d12_mmt_{name}.hlsl"
        for w in WIDTHS:
            with tempfile.TemporaryDirectory() as td:
                obj = Path(td) / "out.dxil"
                cmd = [dxc, "-T", "cs_6_4", "-E", "CSMain", "-D", f"NUM_THREADS={w}", "-D", f"TILE={TILE}",
                       "-I", str(ROOT / "shaders"), "-Fo", str(obj), str(src)]
                subprocess.run(cmd, check=True)
                emit(obj.read_bytes(), gen / f"ggml_d3d12_mmt_{name}_t{w}_dxil.h",
                     f"shaders/ggml_d3d12_mmt_{name}.hlsl -D NUM_THREADS={w} -D TILE={TILE}",
                     f"kGgmlD3d12Mmt{camel}T{w}Dxil")


if __name__ == "__main__":
    main()
